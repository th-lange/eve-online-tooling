// Generates src/theme-light.css: the Light theme, expressed as a remap of
// Tailwind's colour palette (#1213, stage 2).
//
// The app is written with raw palette utilities (bg-zinc-900, text-rose-400,
// ...) in ~160 files. Instead of rewriting every class, Light redefines the
// palette variables themselves under `:root[data-theme="light"]`, so every
// existing utility resolves to a light-appropriate colour in one place:
//
//   neutrals (zinc, slate): the scale is mirrored  (950 <-> 50, 900 <-> 100, ...)
//   accents (rose, amber, emerald, indigo, ...):
//     - light text shades 100-400 become dark shades so text stays readable
//       on a light page (400 -> 700 and 300 -> 800 keep WCAG AA on white)
//     - dark tint shades 800-950 (used for tinted backgrounds and borders)
//       become light tints (200/100/50)
//     - 500-700 (solid fills carrying white text, checkbox accents, a few
//       text uses) shift one step darker (500 -> 600, 600 -> 700): white text
//       on a primary button gets more contrast, and 500-shade text gets closer
//       to readable
//   neutral 500 (the most common muted-text shade) is darkened slightly more
//   than the mirror gives, so muted text keeps ~4.5:1 on panels.
//
// Usage:  node scripts/gen-light-palette.mjs > src/theme-light.css
// (reads node_modules/tailwindcss/theme.css so the values are never hand-typed)
import { readFileSync } from "node:fs";

const theme = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const NEUTRAL = ["zinc", "slate"];
const ACCENT = [
  "rose",
  "red",
  "orange",
  "amber",
  "yellow",
  "emerald",
  "teal",
  "sky",
  "blue",
  "indigo",
  "violet",
  "purple",
  "fuchsia",
];

const neutralMap = {
  50: 950,
  100: 900,
  200: 800,
  300: 700,
  400: 600,
  500: 500,
  600: 400,
  700: 300,
  800: 200,
  900: 100,
  950: 50,
};
const accentMap = {
  50: 950,
  100: 950,
  200: 900,
  300: 800,
  400: 700,
  500: 600,
  600: 700,
  700: 700,
  800: 200,
  900: 100,
  950: 50,
};

// Light-theme override for neutral 500: same hue/chroma, 3 points darker.
function darkened(oklch, by) {
  const m = oklch.match(/^oklch\(([\d.]+)%\s+(.*)\)$/);
  return `oklch(${(parseFloat(m[1]) - by).toFixed(1)}% ${m[2]})`;
}

function value(palette, shade) {
  const m = theme.match(new RegExp(`--color-${palette}-${shade}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing --color-${palette}-${shade}`);
  return m[1].trim();
}

const out = [];
out.push(
  "/* GENERATED by scripts/gen-light-palette.mjs — do not edit by hand.",
  " * Light theme (#1213): remaps the Tailwind palette so existing utilities",
  " * (bg-zinc-900, text-rose-400, ...) resolve to light-appropriate colours.",
  " * See the script header for the mapping rules. */",
  ':root[data-theme="light"] {',
);
for (const [palettes, map] of [
  [NEUTRAL, neutralMap],
  [ACCENT, accentMap],
]) {
  for (const p of palettes) {
    for (const s of shades) {
      let v = value(p, map[s]);
      if (map === neutralMap && s === 500) v = darkened(v, 3);
      out.push(`  --color-${p}-${s}: ${v};`);
    }
  }
}
out.push("}", "");
process.stdout.write(out.join("\n"));
